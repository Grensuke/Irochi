# Function to recursively merge custom translations over English base
def merge_locale(base, override):
    result = {}
    for k, v in base.items():
        if k in override:
            if isinstance(v, dict) and isinstance(override[k], dict):
                result[k] = merge_locale(v, override[k])
            else:
                result[k] = override[k]
        else:
            result[k] = v
    # Also add any keys in override that aren't in base
    for k, v in override.items():
        if k not in result:
            result[k] = v
    return result

